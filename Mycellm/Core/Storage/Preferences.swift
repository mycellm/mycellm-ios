    /// A fresh management key.
    ///
    /// 160 bits from the system CSPRNG, hex-encoded — long enough that the
    /// per-IP lockout in `NodeAuth` is defence in depth rather than the only
    /// thing standing between a LAN guest and this node's model management.
    /// Prefixed so it is recognisable in a config file or a log line.
    static func generateAPIKey() -> String {
        var bytes = [UInt8](repeating: 0, count: 20)
        if SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes) != errSecSuccess {
            // SecRandom failing is not a reason to hand back something
            // guessable; UUIDs are also CSPRNG-backed on Apple platforms.
            return "mck_" + (UUID().uuidString + UUID().uuidString)
                .replacingOccurrences(of: "-", with: "").lowercased().prefix(40)
        }
        return "mck_" + bytes.map { String(format: "%02x", $0) }.joined()
    }

    /// Mint a management key on first launch if there isn't one.
    ///
    /// ⚠️ A DELIBERATE DIVERGENCE FROM THE PYTHON NODE, WHICH DOES NOT DO THIS.
    /// There, `api_key` defaults to empty and the operator sets
    /// `MYCELLM_API_KEY`; a keyless daemon is still fully manageable over
    /// loopback by someone with a shell on the box. iOS has no env, no config
    /// file and no shell, so "loopback only" is not a stricter default there —
    /// it means the management surface can never be reached by anything, which
    /// is exactly the state every build from 1.1.0 shipped in.
    ///
    /// Generating one is not a weaker posture. The gate is possession of the
    /// key: without one the surface is closed to the LAN, with one it is closed
    /// to everyone who hasn't got 160 unguessable bits. That is a lock fitted
    /// rather than a door welded shut.
    ///
    /// ⚠️ THE FLEET KEY IS POINTEDLY NOT AUTO-GENERATED. It is a shared secret
    /// that enrols this device in remote management by whoever administers a
    /// network — a trust decision the owner has to make, not one to make for
    /// them. Device-local root: generated. Cross-node authority: opt-in.
    @discardableResult
    func ensureAPIKey() -> String {
        let existing = apiKey
        guard existing.isEmpty else { return existing }
        let fresh = Self.generateAPIKey()
        apiKey = fresh
        return fresh
    }

