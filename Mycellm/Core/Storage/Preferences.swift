    ///
    /// ⚠️ TAKES EFFECT AT NEXT LAUNCH, NOT IMMEDIATELY. SwiftData fixes
    /// `cloudKitDatabase` per configuration at creation, so applying a change
    /// means rebuilding the container — and rebuilding it live meant tearing
    /// the whole view tree down and back up, which threw the user out of
