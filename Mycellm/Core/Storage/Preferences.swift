import Foundation

/// UserDefaults wrapper for app preferences.
///
/// ⚠️ EVERY ACCESSOR CALLS `access` / `withMutation` BY HAND, AND HAS TO.
/// `@Observable` instruments *stored* properties; these are computed properties
/// over UserDefaults, so the macro wires up nothing for them and SwiftUI
/// registers no dependency. Reads never became dependencies and writes never
/// invalidated anything, so a view reading one of these simply did not update:
/// a toggle wrote its value and the surrounding `if` never re-evaluated, a
/// Picker wrote a selection and kept showing the old one. Three separate
/// "the control doesn't work" bugs traced back here — the HTTP Server toggle
/// hiding the API key row, the Privacy Guard section, and the screensaver
/// delay picker — before it was worth fixing the cause rather than the symptoms.
///
/// `access` and `withMutation` are generated by the macro and are exactly what
/// it emits for stored properties; calling them explicitly gives a computed
/// property the same observation behaviour.
@Observable
